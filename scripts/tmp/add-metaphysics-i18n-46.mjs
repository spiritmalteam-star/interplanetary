// per-language sanity before splicing
let fatal = 0;
for (const lang of Object.keys(T)) {
  const d = T[lang];
  for (const k of ORDER) {
    if (!(k in d)) {
      console.error(`[${lang}] MISSING translation for: ${k}`);
      fatal++;
      continue;
    }
    const v = d[k];
    for (const [ch, name] of [["—", "em dash"], ["…", "ellipsis"], ["·", "middle dot"]]) {
      if (count(k, ch) !== count(v, ch)) {
        console.error(`[${lang}] ${name} mismatch (${count(k, ch)} vs ${count(v, ch)}): ${k}`);
        fatal++;
      }
    }
    if ((lang === "fr" || lang === "it") && v.includes("’")) {
      console.error(`[${lang}] curly apostrophe in value: ${k}`);
      fatal++;
    }
    if (v === k) {
      // informational only (check-i18n treats these as NOTE); allowed when the word genuinely matches
      console.log(`[${lang}] NOTE — value identical to English: ${k}`);
    }
    if ((lang === "fr" || lang === "es") && k.trim().endsWith("?") && !v.includes("?")) {
      console.error(`[${lang}] question key without ? in value: ${k}`);
      fatal++;
    }
  }
  for (const k of Object.keys(d)) {
    if (!ORDER.includes(k)) {
      console.error(`[${lang}] EXTRA key not in ORDER: ${k}`);
      fatal++;
    }
  }
}
if (fatal) {
  console.error(`ABORT — ${fatal} problem(s)`);
  process.exit(1);
}

const pairRe = /"((?:[^"\\]|\\.)*)"\s*:\s*"((?:[^"\\]|\\.)*)"/g;
const LANGS = ["sq", "it", "el", "de", "fr", "es", "tr"];
const HEADER =
  "  /* ---- additions: Task 46 — the Metaphysics scope (identity · veil rail · schools & veils · 66 questions) ---- */";

for (const lang of LANGS) {
  const path = `/home/z/my-project/src/lib/i18n/dicts/${lang}.ts`;
  const src = readFileSync(path, "utf8");

  const present = new Set();
  let m;
  pairRe.lastIndex = 0;
  while ((m = pairRe.exec(src))) {
    present.add(m[1].replace(/\\"/g, '"').replace(/\\\\/g, "\\"));
  }
  const before = present.size;

  const entries = [];
  const skipped = [];
  for (const k of ORDER) {
    if (present.has(k)) {
      skipped.push(k);
      continue;
    }
    entries.push(`  ${JSON.stringify(k)}: ${JSON.stringify(T[lang][k])},`);
  }

  const idx = src.lastIndexOf("};");
  if (idx === -1) throw new Error(`no closing }; in ${lang}`);
  const block = HEADER + "\n" + entries.join("\n") + "\n";
  const out = src.slice(0, idx) + block + src.slice(idx);
  writeFileSync(path, out, "utf8");

  // re-parse: count entries + duplicate audit
  const after = readFileSync(path, "utf8");
  const seen = new Map();
  let dup = 0;
  pairRe.lastIndex = 0;
  while ((m = pairRe.exec(after))) {
    const k = m[1].replace(/\\"/g, '"').replace(/\\\\/g, "\\");
    if (seen.has(k)) {
      dup++;
      console.error(`[${lang}] DUPLICATE KEY: ${k}`);
    }
    seen.set(k, m[2]);
  }
  console.log(
    `[${lang}] entries ${before} → ${seen.size} | added ${entries.length} | skipped ${skipped.length}${skipped.length ? " : " + skipped.join(" ; ") : ""} | duplicates: ${dup}`
  );
}
