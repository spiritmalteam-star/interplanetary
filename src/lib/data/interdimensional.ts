function attach(group: RawGroup): InterdimGroup {
  const representatives = interdimEntities.filter(
    (e) => e.groupId === group.id
  );
  return { ...group, count: representatives.length, representatives };
}

export const interdimensional: InterdimGroup[] = raw.map(attach);

export const interdimTotal = interdimensional.reduce((s, c) => s + c.count, 0);

export function findInterdimRepresentative(id: string): EntityDossier | null {
  return interdimEntities.find((e) => e.id === id) ?? null;
}
